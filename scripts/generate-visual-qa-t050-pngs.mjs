async function main() {
  const browser = await chromium.launch({
    headless: true,
    executablePath: CHROMIUM_PATH,
  });
  try {
    const context = await browser.newContext({
      viewport: VIEWPORT,
      deviceScaleFactor: 2,
    });
    const page = await context.newPage();
    for (const state of STATES) {
      const html = await readFile(
        resolve(VISUAL_QA_DIR, `t050-${state.label}.html`),
        "utf8",
      );
      const full = HTML_DOC({
        body: html,
        eyebrow: state.eyebrow,
        title: state.title,
        subtitle: state.subtitle,
      });
      await page.setContent(full, { waitUntil: "load" });
      await page.screenshot({
        path: resolve(OUTPUT_DIR, `t050-${state.label}.png`),
        fullPage: true,
      });
      console.log(`[visual-qa-t050] wrote t050-${state.label}.png`);
    }
    await context.close();
  } finally {
    await browser.close();
  }
}

try {
  await main();
} catch (err) {
  console.error("[visual-qa-t050] PNG generation failed:", err);
  process.exitCode = 1;
}

